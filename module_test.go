// Module zips omit vendor directories regardless of whether they contain Go
// packages. Check the entire tree, including the nested coexistence module.
func TestModuleHasNoVendorDirectories(t *testing.T) {
	err := filepath.WalkDir(".", func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() {
			return nil
		}
		if path == ".git" || path == "build" || entry.Name() == "testdata" {
			return filepath.SkipDir
		}
		if entry.Name() == "vendor" {
			t.Errorf("%s: vendor directories are omitted from Go module zips", path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

// Check every component: an existing file can still be omitted because it is
// reached through a symlink, a VCS directory or a nested module.
func checkModuleSourcePath(t *testing.T, path string) {
	t.Helper()
	path = filepath.Clean(path)
	if filepath.IsAbs(path) || path == ".." || strings.HasPrefix(path, ".."+string(filepath.Separator)) {
		t.Errorf("%s: source path leaves the module", path)
		return
	}
	current := "."
	for _, part := range strings.Split(path, string(filepath.Separator)) {
		current = filepath.Join(current, part)
		switch part {
		case "vendor", ".git", ".hg", ".svn", ".bzr", ".hg_archival.txt":
			t.Errorf("%s: excluded module zip path component %s", path, part)
		}
		info, err := os.Lstat(current)
		if err != nil {
			t.Errorf("%s: %v", path, err)
			return
		}
		if info.IsDir() {
			if _, err := os.Stat(filepath.Join(current, "go.mod")); current != "." && err == nil {
				t.Errorf("%s: nested module at %s is omitted from the module zip", path, current)
			}
		} else if !info.Mode().IsRegular() {
			t.Errorf("%s: non-regular source at %s is omitted from module zips", path, current)
			return
		}
	}
}

func TestCgoModulePaths(t *testing.T) {
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatal(err)
	}
	localPath := regexp.MustCompile(`\$\{SRCDIR\}/([^\s]+)`)
	quotedInclude := regexp.MustCompile(`(?m)^\s*#include\s+"([^"]+)"`)
	includeDirs := []string{"."} // cgo always adds the package directory.
	var includes []string
	for _, entry := range entries {
		switch filepath.Ext(entry.Name()) {
		case ".go", ".c", ".h", ".m":
		default:
			continue
		}
		data := string(read(t, entry.Name()))
		for _, line := range strings.Split(data, "\n") {
			if !strings.HasPrefix(line, "#cgo ") {
				continue
			}
			for _, match := range localPath.FindAllStringSubmatch(line, -1) {
				path := filepath.FromSlash(match[1])
				checkModuleSourcePath(t, path)
				if info, err := os.Stat(path); err == nil && info.IsDir() {
					includeDirs = append(includeDirs, path)
				}
			}
		}
		for _, match := range quotedInclude.FindAllStringSubmatch(data, -1) {
			includes = append(includes, match[1])
		}
	}
	if len(includeDirs) == 1 || len(includes) == 0 {
		t.Fatal("no local cgo include paths or files checked")
	}
	for _, name := range includes {
		if name == "_cgo_export.h" { // Generated by cgo during each build.
			continue
		}
		found := false
		for _, dir := range includeDirs {
			path := filepath.Join(dir, filepath.FromSlash(name))
			if info, err := os.Stat(path); err == nil && info.Mode().IsRegular() {
				checkModuleSourcePath(t, path)
				found = true
				break
			}
		}
		if !found {
			t.Errorf("local cgo include %q does not exist in %v", name, includeDirs)
		}
	}
	// This also covers angle-bracket includes such as the SQLite amalgamation,
	// and all snnote/snrender sources, including the inactive backend's files.
	err = filepath.WalkDir("internal/clib", func(path string, _ fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		checkModuleSourcePath(t, path)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}
