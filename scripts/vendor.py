"""Vendor pinned production sources and verify symbol isolation on both backends.

Run on macOS with the Cairo pkg-config dependencies installed. Staging and
compiler outputs remain below build/, so failed generation leaves sources alone.
Git is only used to read immutable objects; checkout modifications are irrelevant.
"""
import argparse
import concurrent.futures
import hashlib
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import tempfile

PINS = {'snspd': '0ac7ba43dcf4b798d9ac5c845dc2eee2b7d45b3b',
        'snnote': '2cab83674ba017abe0e0e42eb5b6e5558a27155f',
        'snrender': '032b7048d29617c8b9861256b59c3cf9a7bf578f'}
VERSIONS = {'snspd': 'v1.0.0', 'snnote': 'v1.0.0', 'snrender': 'v1.0.0'}
# Match snspd-lib CMakeLists.txt. SQLite is static inside spd_parser.c.
SQLITE = '''OS_OTHER=1 THREADSAFE=0 DEFAULT_MEMSTATUS=0 ZERO_MALLOC=1
OMIT_LOAD_EXTENSION=1 DQS=0 OMIT_WAL=1 OMIT_SHARED_CACHE=1 OMIT_UTF16=1
OMIT_DEPRECATED=1 OMIT_TCL_VARIABLE=1 OMIT_TRACE=1 OMIT_LOCALTIME=1 TEMP_STORE=3
DEFAULT_LOOKASIDE=0,0 ENABLE_API_ARMOR=1 MAX_LENGTH=67108864 MAX_SQL_LENGTH=4096
MAX_COLUMN=32 MAX_EXPR_DEPTH=32 MAX_VARIABLE_NUMBER=8'''.split()
PACKAGES = ['cairo', 'cairo-ft', 'freetype2', 'gdk-pixbuf-2.0', 'zlib']
APPLE = 'darwin && !snrender_cairo'
CAIRO = 'linux || windows || (darwin && snrender_cairo)'
HEADER = ('// Copyright 2026 ALTESSA SOLUTIONS INC.\n'
          '// Use of this source code is governed by an MIT-style license that can be\n'
          '// found in the LICENSE file.\n\n'
          '// Generated by scripts/vendor.py; do not edit.\n')


def run(args):
    return subprocess.check_output(args, stderr=subprocess.STDOUT).decode()


def production(text):
    # These two conditional blocks are the upstream allocation-failure hooks.
    lines, keep, stack = [], True, []
    for line in text.splitlines(keepends=True):
        if line.startswith('#ifdef SNR_TESTING'):
            stack.append(keep)
            keep = False
        elif stack and line.startswith('#else'):
            keep = stack[-1]
        elif stack and line.startswith('#endif'):
            keep = stack.pop()
        elif keep:
            lines.append(line)
    result = ''.join(lines)
    if stack or 'SNR_TESTING' in result:
        raise ValueError('unrecognized testing conditional')
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for lib in PINS:
        p.add_argument('--' + lib, required=True, type=Path)
    p.add_argument('--cc', default=os.environ.get('CC', 'cc'))
    p.add_argument('--pdfium', required=True, type=Path,
                   help='PDFium SDK fetched by snrender/scripts/fetch-pdfium.py')
    args = p.parse_args()
    root = Path(__file__).resolve().parent.parent
    (root / 'build').mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=root / 'build', prefix='vendor-') as tmp:
        stage = Path(tmp)
        clib = stage / 'internal/clib'
        wrappers = []
        for lib, pin in PINS.items():
            source = getattr(args, lib).resolve()
            files = run(['git', '-C', str(source), 'ls-tree', '-r', '--name-only', pin]).splitlines()
            for name in files:
                wanted = name in ('LICENSE', 'COPYRIGHT') or name.startswith(('src/', 'include/'))
                if lib == 'snspd':
                    wanted |= name.startswith('vendor/sqlite/')
                if lib == 'snrender':
                    wanted |= name.startswith(('backends/apple/', 'backends/linux/'))
                    wanted |= name == 'scripts/fetch-pdfium.py'
                if not wanted:
                    continue
                data = subprocess.check_output(['git', '-C', str(source), 'show', pin + ':' + name])
                if lib == 'snrender' and name.endswith(('.c', '.h', '.m')):
                    data = production(data.decode()).encode()
                # Module zips omit vendor directories, even for C sources.
                target_name = name.removeprefix('vendor/') if lib == 'snspd' else name
                dest = clib / lib / target_name
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(data)
                if name.endswith(('.c', '.m')) and not name.startswith('vendor/'):
                    constraint = APPLE if '/apple/' in name else CAIRO if '/linux/' in name else None
                    wrapper = 'clib_' + lib + '_' + name.replace('/', '_')
                    text = HEADER
                    if constraint:
                        text += '//go:build ' + constraint + '\n'
                    if lib == 'snspd' and name == 'src/spd_parser.c':
                        text += '\n' + ''.join('#define SQLITE_' + d.replace('=', ' ', 1) + '\n' for d in SQLITE)
                    text += '\n#include "clib_digest.h"\n#include "internal/clib/' + lib + '/' + name + '"\n'
                    (stage / wrapper).write_text(text)
                    wrappers.append((wrapper, constraint))
        (clib / 'VERSION').write_text(''.join(f'{lib}-lib {VERSIONS[lib]} {pin}\n' for lib, pin in PINS.items()))
        renderer_version = next(line.split()[1] for line in (clib / 'VERSION').read_text().splitlines()
                                if line.startswith('snrender-lib '))
        (stage / 'clib_version.go').write_text(HEADER + '\npackage snrender\n\n'
            '// LibraryVersion is the version of snrender-lib recorded in internal/clib/VERSION.\n'
            f'const LibraryVersion = "{renderer_version}"\n')
        digest = hashlib.sha256()
        for f in sorted(clib.rglob('*')):
            if f.is_file():
                digest.update(f'{hashlib.sha256(f.read_bytes()).hexdigest()} {f.relative_to(clib)}\n'.encode())
        (stage / 'clib_digest.h').write_text(HEADER + '#define SNRGO_DIGEST "' + digest.hexdigest() + '"\n' + ''.join(f'#define SNRGO_{lib.upper()}_COMMIT "{pin}"\n' for lib, pin in PINS.items()))
        flags = ['-std=c2x', '-ffp-contract=off', '-fvisibility=hidden', '-w', '-DSNR_SPD', '-I' + str(stage)]
        for lib in PINS:
            flags += ['-I' + str(clib / lib / 'include'), '-I' + str(clib / lib / 'src')]
        flags += ['-I' + str(clib / 'snspd/sqlite')]
        cairo = shlex.split(run(['pkg-config', '--cflags', *PACKAGES])) + [
            '-DSNR_CAIRO_BACKEND', '-DSNR_PDFIUM', '-I' + str(args.pdfium.resolve() / 'include')]
        jobs = [(name, backend) for name, tag in wrappers for backend in ('apple', 'cairo')
                if tag is None or tag == (APPLE if backend == 'apple' else CAIRO)]

        def symbols(prefixed):
            def build(job):
                name, backend = job
                out = stage / (backend + name + '.o')
                opts = flags + (cairo if backend == 'cairo' else [])
                if name.endswith('.m'):
                    opts += ['-fobjc-arc']
                if prefixed:
                    opts += ['-include', str(stage / 'clib_symbols.h')]
                run([args.cc, *opts, '-c', str(stage / name), '-o', str(out)])
                found = set()
                for line in run(['nm', '-g', str(out)]).splitlines():
                    fields = line.split()
                    if len(fields) >= 3 and fields[-2] not in ('U', 'u', 'w', 'v'):
                        found.add(fields[-1].removeprefix('_'))
                return found
            with concurrent.futures.ThreadPoolExecutor() as pool:
                return set().union(*pool.map(build, jobs))
        names = symbols(False)
        if not names or any(not n.startswith(('sn_', 'snr_', 'spe_', 'spd_')) for n in names):
            raise ValueError('unexpected external symbols: ' + repr(names))
        (stage / 'clib_symbols.h').write_text(HEADER + ''.join(f'#define {n} snrgo_{n}\n' for n in sorted(names)))
        renamed = symbols(True)
        if renamed != {'snrgo_' + n for n in names}:
            raise ValueError('symbol isolation failed: ' + repr(renamed))
        target = root / 'internal/clib'
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(clib, target)
        for old in [*root.glob('clib_*.c'), *root.glob('clib_*.m')]:
            old.unlink()
        for name in [n for n, _ in wrappers] + ['clib_symbols.h', 'clib_digest.h', 'clib_version.go']:
            shutil.copyfile(stage / name, root / name)
        print(f'Vendored {len(wrappers)} sources, {len(names)} isolated symbols, digest {digest.hexdigest()}')


if __name__ == '__main__':
    main()
